#!/usr/bin/env python3
"""Embed web/index.html into src/kbm_webui_gen.h as a NUL-terminated byte array."""
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
src = root / "web" / "index.html"
dst = root / "src" / "kbm_webui_gen.h"
data = src.read_bytes() + b"\0"
lines = ["/* GENERATED by tools/embed_web.py from web/index.html — do not edit. */",
         "#pragma once",
         f"static const char KBM_WEBUI_HTML[{len(data)}] = {{"]
for i in range(0, len(data), 20):
    lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i+20]) + ",")
lines.append("};")
dst.write_text("\n".join(lines) + "\n")
print(f"embedded {len(data)-1} bytes -> {dst.relative_to(root)}")
